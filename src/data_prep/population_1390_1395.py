df_pop = pd.DataFrame(data)

# محاسبه سال‌های بین 1391 تا 1394 و سال 1395 بر اساس نرخ رشد
years = [1391, 1392, 1393, 1394, 1395]
for year in years:
    n = year - 1390
    df_pop[str(year)] = df_pop['Pop_1390'] * (1 + df_pop['Growth_Rate']/100)**n

# مرتب‌سازی و ذخیره
df_pop['1390'] = df_pop['Pop_1390']
final_cols = ['نام استان'] + [str(y) for y in range(1390, 1396)]
df_pop_final = df_pop[final_cols].round(0).astype({str(y): int for y in range(1390, 1396)})

# ذخیره در فایل اکسل
output_path = str(ROOT / "data/Pop/Population_90_95.xlsx")
df_pop_final.to_excel(output_path, index=False)

